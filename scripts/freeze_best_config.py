#!/usr/bin/env python3
"""Phase 11a: freeze configs/best.yaml from the tuning-split decisions (plan 11.1-11.2 / docs/design.md §13.9).

Usage:
    python scripts/freeze_best_config.py [--overwrite]

Reads data/artifacts/variant_v1..v4_decision.json, pool_size_decision.json and the Core tuning file; writes
configs/best.yaml (choice, evidence and rationale per part). Run after scripts/decide_pool_size.py and before any
Phase 11 comparison system is run on the test split. Refuses to overwrite a frozen file without --overwrite.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import shutil
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from paperfeed.common.config import load_config
from paperfeed.common.manifest import RunManifest
from paperfeed.eval.best_config import build_best_config
from paperfeed.eval.tuning import find_tuning_artifact, tuning_signature
from paperfeed.rec.recommender import RecommendConfig


def main() -> int:
    parser = argparse.ArgumentParser(description="Freeze configs/best.yaml from the tuning-split decisions.")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    root = Path(__file__).resolve().parent.parent
    cfg = load_config()
    out = root / "configs" / "best.yaml"
    if out.exists() and not args.overwrite:
        print(f"{out} already exists: it is frozen. Pass --overwrite only if it must be redone.", file=sys.stderr)
        return 1
    artifacts = root / cfg["paths"]["artifacts_dir"]
    processed = root / cfg["paths"]["processed_dir"]
    cohort = [json.loads(l) for l in open(processed / "cohort.jsonl", encoding="utf-8") if l.strip()]
    core_sig = tuning_signature(RecommendConfig.from_config(cfg), [a["author_id"] for a in cohort if a.get("split") == "tuning"])
    core_file = find_tuning_artifact(artifacts, core_sig)
    if core_file is None:
        raise FileNotFoundError("No Core tuning file matches the headline configuration; run scripts/run_track1_eval.py.")

    run_id = f"best_config_{datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')}"
    manifest = RunManifest(run_id, cfg, runs_dir=root / "results" / "runs")
    try:
        best = build_best_config(artifacts, core_file.name, cfg)
        if best["assembled_check"].startswith("Multiple"):
            raise RuntimeError("More than one component was replaced: run the §13.9 assembled-system check first.")
        best["frozen_at"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        header = ("# Best configuration (plan Phase 11.1-11.2, docs/design.md §13.9). Generated by\n"
                  "# scripts/freeze_best_config.py from tuning-split decisions only; do not edit by hand.\n")
        out.write_text(header + yaml.safe_dump(best, sort_keys=False, allow_unicode=True), encoding="utf-8")
        shutil.copy2(out, manifest.run_dir / out.name)
        manifest.complete(metadata={"best_configuration": best["best_configuration"], "output": "configs/best.yaml"})
        print(out.read_text(encoding="utf-8"))
    except BaseException as exc:
        manifest.complete(status="FAILED", metadata={"error": repr(exc)})
        raise
    return 0


if __name__ == "__main__":
    sys.exit(main())
